#pragma once

#include <windows.h>
#include <string>
#include <vector>
#include <functional>

#include "ui/GUI.h"
#include "overlay/OverlayRenderer.h"

// Forward declaration
typedef std::function<void(int sectionIdx, int slotIdx)> SlotClickCallback;
typedef std::function<void(int sectionIdx, int slotIdx, int dx, int dy)> SlotMoveCallback;

// ---------------------------------------------------------------------------
// Создание окна оверлея
// ---------------------------------------------------------------------------
/**
 * Создать окно оверлея с DirectX 11 рендерингом.
 * @param width  Ширина окна в пикселях.
 * @param height Высота окна в пикселях.
 * @return true если окно успешно создано.
 */
bool createOverlayWindow(int width, int height);

// ---------------------------------------------------------------------------
// Уничтожение окна оверлея
// ---------------------------------------------------------------------------
/**
 * Уничтожить окно оверлея и освободить ресурсы.
 */
void destroyOverlayWindow();

// ---------------------------------------------------------------------------
// Обновление кадра оверлея
// ---------------------------------------------------------------------------
/**
 * Обновить кадр оверлея новыми данными.
 * @param frame  Данные кадра из GUI.
 * @param colors Цветовая схема.
 */
void updateOverlayFrame(const GUIFrame& frame, const ColorScheme& colors);

// ---------------------------------------------------------------------------
// Показать оверлей
// ---------------------------------------------------------------------------
void showOverlay();

// ---------------------------------------------------------------------------
// Скрыть оверлей
// ---------------------------------------------------------------------------
void hideOverlay();

// ---------------------------------------------------------------------------
// Управление позицией и размером
// ---------------------------------------------------------------------------
/**
 * Установить позицию оверлея.
 * @param x X-координата.
 * @param y Y-координата.
 */
void setOverlayPosition(int x, int y);

/**
 * Установить размер оверлея.
 * @param width  Ширина.
 * @param height Высота.
 */
void setOverlaySize(int width, int height);

// ---------------------------------------------------------------------------
// Установка callback для кликов по индикаторам
// ---------------------------------------------------------------------------
/**
 * Установить callback при клике по индикатору в оверлее.
 * @param callback Функция, принимающая индексы секции и слота.
 */
void setOverlaySlotClickCallback(SlotClickCallback callback);

// ---------------------------------------------------------------------------
// Установка callback для перемещения индикаторов
// ---------------------------------------------------------------------------
/**
 * Установить callback при перемещении индикатора в оверлее.
 * @param callback Функция, принимающая индексы секции, слота и смещение.
 */
void setOverlaySlotMoveCallback(SlotMoveCallback callback);

// ---------------------------------------------------------------------------
// Установка выделенных слотов
// ---------------------------------------------------------------------------
/**
 * Установить список выделенных слотов для перемещения.
 * @param sectionIdx Индекс секции.
 * @param slotIdx Индекс слота.
 * @param offsetX Сдвиг по X.
 * @param offsetY Сдвиг по Y.
 */
void setOverlaySelectedSlot(int sectionIdx, int slotIdx, int offsetX, int offsetY);

/**
 * Сбросить выделенный слот.
 */
void clearOverlaySelectedSlot();

// ---------------------------------------------------------------------------
// Установка списка выделенных слотов
// ---------------------------------------------------------------------------
/**
 * Установить список выделенных слотов для перемещения.
 */
void setOverlaySelectedSlotInfos(const std::vector<SelectedSlotInfo>& infos);
